def test_41_research_context_contains_no_forbidden_recommendation_terms(dummy_context):
    """ResearchSignalContext fields contain zero prohibited recommendation terms."""
    dump_str = json.dumps(dummy_context.model_dump(), default=str).upper()
    for term in ["BUY_RECOMMENDED", "SELL_RECOMMENDED", "PROMOTED_TO_LIVE", "GUARANTEED"]:
        assert term not in dump_str


def test_42_no_buy_sell_recommendation_in_research_context(dummy_context):
    """Research context does not contain actionable trade recommendations."""
    assert not hasattr(dummy_context, "action")
    assert not hasattr(dummy_context, "direction")
    assert not hasattr(dummy_context, "recommended_action")


def test_43_no_ranking_fields_are_added(dummy_context):
    """Research context schemas contain zero ranking fields."""
    d = dummy_context.model_dump()
    for rank_field in ["rank", "score_rank", "tier", "grade", "win_rate_rank"]:
        assert rank_field not in d


def test_44_no_best_edge_winning_superlatives_in_research_context(dummy_context):
    """Prohibited marketing superlatives are completely absent from research context."""
    dump_str = json.dumps(dummy_context.model_dump(), default=str).upper()
    for word in ["BEST", "EDGE", "ALPHA", "WINNING"]:
        # Word boundary assertion
        import re
        matches = re.findall(rf"\b{word}\b", dump_str)
        assert len(matches) == 0, f"Found forbidden term '{word}' in research context!"


def test_45_candidate_wording_remains_immutable(dummy_context):
    """Candidate wording and identity remain descriptive and immutable."""
    assert dummy_context.candidate_id == "HYP-EURUSD-1H-H5-001"
    assert dummy_context.methodology_version == "1.0.0"
