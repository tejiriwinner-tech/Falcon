def test_32_research_integration_zero_db_writes(monkeypatch, engine, mock_market_state, mock_strategy, dummy_context):
    """Research integration produces zero database writes/commits/adds."""
    def forbidden_write(*args, **kwargs):
        pytest.fail("Database write operation attempted during research promotion / signal pipeline!")

    monkeypatch.setattr("sqlalchemy.orm.Session.add", forbidden_write, raising=False)
    monkeypatch.setattr("sqlalchemy.orm.Session.commit", forbidden_write, raising=False)
    monkeypatch.setattr("sqlalchemy.orm.Session.delete", forbidden_write, raising=False)

    # Generate signals with research context
    cands = engine.generate_candidates(
        mock_market_state,
        [mock_strategy],
        research_contexts={"EURUSD": dummy_context},
    )
    assert len(cands) == 1
    assert cands[0].researchContext == dummy_context


