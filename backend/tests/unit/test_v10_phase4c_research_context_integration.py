def test_37_identical_inputs_produce_identical_research_context(engine, dummy_context):
    """Deterministic matching produces bitwise identical context for repeated calls."""
    m1 = engine.match_research_context("EURUSD", "1H", "LOWER_PRICE_REJECTION", "UPTREND", 5, [dummy_context])
    m2 = engine.match_research_context("EURUSD", "1H", "LOWER_PRICE_REJECTION", "UPTREND", 5, [dummy_context])
    assert m1 == m2
    assert m1.model_dump() == m2.model_dump()


def test_38_missing_research_candidate_produces_none(engine, dummy_context):
    """Missing research candidate produces None (fail closed)."""
    res = engine.match_research_context("XAUUSD", "1H", "HAMMER", "UPTREND", 5, [dummy_context])
    assert res is None


def test_39_research_service_failure_does_not_suppress_ordinary_signals(engine, mock_market_state, mock_strategy):
    """If research contexts is corrupted or raises, ordinary signal generation continues unaffected."""
    # Pass an invalid research context structure
    cands = engine.generate_candidates(
        mock_market_state,
        [mock_strategy],
        research_contexts=None,
    )
    assert len(cands) == 1
    baseline = engine.generate_candidates(mock_market_state, [mock_strategy])
    assert cands[0].direction == baseline[0].direction


def test_40_no_fabricated_research_context_is_created(engine):
    """Context is never fabricated when matching candidates do not exist."""
    res = engine.match_research_context("USDJPY", "15M", "NONEXISTENT", "UNKNOWN", 5, [])
    assert res is None


