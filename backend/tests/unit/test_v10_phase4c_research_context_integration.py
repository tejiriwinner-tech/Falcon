def test_28_forward_validation_strictly_candidate_as_of_less_than_t0(service):
    """Forward validation observations must be strictly after candidate_as_of."""
    t0 = datetime(2026, 8, 1, 0, 0, tzinfo=timezone.utc)
    base_obs = [
        make_synthetic_obs(f"BASE-{i:03d}", t0 + timedelta(hours=i))
        for i in range(50)
    ]
    cand_as_of = base_obs[-1].observation_time
    val_as_of = cand_as_of + timedelta(days=10)

    # Observation exactly AT candidate_as_of is excluded
    obs_boundary = make_synthetic_obs("OBS-AT-BOUNDARY", cand_as_of)
    # Observation strictly after candidate_as_of is included
    obs_after = make_synthetic_obs("OBS-AFTER", cand_as_of + timedelta(hours=1))

    resp = service.get_forward_validation(
        instrument="EURUSD",
        timeframe="1h",
        horizon=5,
        candidate_as_of=cand_as_of,
        validation_as_of=val_as_of,
        observations=base_obs + [obs_boundary, obs_after],
    )
    assert resp.total_forward_observations == 1


def test_29_monitoring_population_not_merged_with_forward_validation(service):
    """Monitoring observations and forward validation are kept strictly partitioned."""
    cand_as_of = datetime(2026, 8, 1, 0, 0, tzinfo=timezone.utc)
    val_as_of = datetime(2026, 9, 1, 0, 0, tzinfo=timezone.utc)

    # An observation after validation_as_of cannot enter forward validation
    obs_monitoring = make_synthetic_obs("OBS-MONITORING", val_as_of + timedelta(days=1))

    resp = service.get_forward_validation(
        instrument="EURUSD",
        timeframe="1h",
        horizon=5,
        candidate_as_of=cand_as_of,
        validation_as_of=val_as_of,
        observations=[obs_monitoring],
    )
    assert resp.total_forward_observations == 0


